def compute_rollout(attentions):
    stacked = torch.stack(attentions, dim=0)
    avg_heads = stacked.mean(dim=2)
    num_layers, batch, seq, _ = avg_heads.shape
    I = torch.eye(seq, device=avg_heads.device).unsqueeze(0).unsqueeze(0)
    avg_heads = avg_heads + I
    avg_heads = avg_heads / avg_heads.sum(dim=-1, keepdim=True)
    rollout = avg_heads[0]
    for l in range(1, num_layers):
        rollout = torch.bmm(rollout, avg_heads[l])
    return rollout

def get_token_importance(text, max_len=128):
    enc = tokenizer(text, return_tensors="pt", truncation=True,
                    max_length=max_len).to(DEVICE)
    with torch.no_grad():
        out = model(**enc)
    rollout = compute_rollout(out.attentions)
    cls_att = rollout[0, 0, :].cpu().numpy()
    toks = tokenizer.convert_ids_to_tokens(enc["input_ids"].cpu().numpy()[0])
    return [(t.replace("Ġ", ""), float(i))
            for t, i in zip(toks, cls_att)
            if t not in ["<s>", "</s>", "<pad>"]]

