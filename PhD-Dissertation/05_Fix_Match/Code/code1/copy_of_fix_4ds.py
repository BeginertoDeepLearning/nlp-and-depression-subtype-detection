    CLINICAL_NEGATIONS = {"not", "no", "never", "barely", "hardly",
                          "dont", "cant", "wont", "isnt", "wasnt", "arent"}

    def weak_augment(text, drop_prob=0.05):
        toks = str(text).split()
        if len(toks) <= 3: return str(text)
        kept = [t for t in toks
                if (t.lower() in CLINICAL_NEGATIONS) or (random.random() > drop_prob)]
        return " ".join(kept) if len(kept) >= 3 else str(text)

    def strong_augment(text, drop_prob=0.15):
        sents = [s.strip() for s in str(text).replace("\n", ".").split(". ") if s.strip()]
        if len(sents) >= 4:
            random.shuffle(sents)
            text = ". ".join(sents)
        toks = str(text).split()
        if len(toks) <= 5: return str(text)
        kept = [t for t in toks
                if (t.lower() in CLINICAL_NEGATIONS) or (random.random() > drop_prob)]
        return " ".join(kept) if len(kept) >= 5 else str(text)

    def tokenize_batch(tk, texts, max_len=128):
        return tk(list(texts), truncation=True, padding=True,
                  max_length=max_len, return_tensors="pt")

    def eval_model(m, tk, df_eval, max_len=128, batch_size=32):
        m.eval()
        all_preds, all_true = [], []
        loader = DataLoader(df_eval.to_dict("records"),
                            batch_size=batch_size, shuffle=False)
        with torch.no_grad():
            for batch in loader:
                enc = tokenize_batch(tk, batch["text"], max_len=max_len)
                enc = {k: v.to(DEVICE) for k, v in enc.items()}
                out = m(**enc)
                preds = torch.argmax(out.logits, dim=-1)
                all_preds.extend(preds.cpu().numpy().tolist())
                all_true.extend(batch["labels"])
        macro = f1_score(all_true, all_preds, average="macro")
        weighted = f1_score(all_true, all_preds, average="weighted")
        return macro, weighted, classification_report(all_true, all_preds, digits=4), confusion_matrix(all_true, all_preds)

    def split_labeled_unlabeled(d, labeled_ratio=0.2):
        labeled_parts, unlabeled_parts = [], []
        for c in sorted(d["labels"].unique()):
            dfc = d[d["labels"] == c].sample(frac=1.0, random_state=SEED)
            n_l = max(1, int(len(dfc) * labeled_ratio))
            labeled_parts.append(dfc.iloc[:n_l])
            unlabeled_parts.append(dfc.iloc[n_l:])
        labeled = pd.concat(labeled_parts).sample(frac=1.0, random_state=SEED).reset_index(drop=True)
        unlabeled = pd.concat(unlabeled_parts).sample(frac=1.0, random_state=SEED).reset_index(drop=True)
        return labeled, unlabeled

    def train_fixmatch(labeled_df, unlabeled_df, dev_df, test_df,
                       model_name, num_labels, max_len=128,
                       batch_size_l=8, batch_size_u=24, lr=2e-5, epochs=20,
                       tau=0.95, lambda_u=1.0, selftrain_top_frac=0.05):

        tokenizer = AutoTokenizer.from_pretrained(model_name, use_fast=True)
        model = AutoModelForSequenceClassification.from_pretrained(
            model_name, num_labels=num_labels).to(DEVICE)
        opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=0.01)

        steps_per_epoch = math.ceil(len(labeled_df) / batch_size_l)
        total_steps = steps_per_epoch * epochs
        scheduler = get_linear_schedule_with_warmup(
            opt, int(0.1 * total_steps), total_steps)

        history = {'epoch': [], 'dev_macro': [], 'train_loss': [],
                   'n_labeled': [], 'n_unlabeled': []}
        best_dev, best_state = -1, None

        for ep in range(1, epochs + 1):
            labeled_loader = DataLoader(labeled_df.to_dict("records"),
                                        batch_size=batch_size_l, shuffle=True)
            unlabeled_loader = DataLoader(unlabeled_df.to_dict("records"),
                                          batch_size=batch_size_u, shuffle=True,
                                          drop_last=True)
            model.train()
            ul_iter = iter(unlabeled_loader)
            total_loss = 0
            t_ep = time.time()

            for lb in labeled_loader:
                try:
                    ub = next(ul_iter)
                except StopIteration:
                    ul_iter = iter(unlabeled_loader)
                    ub = next(ul_iter)

                enc_l = tokenize_batch(tokenizer, lb["text"], max_len)
                enc_l = {k: v.to(DEVICE) for k, v in enc_l.items()}
                y_l = torch.tensor(lb["labels"], dtype=torch.long, device=DEVICE)
                loss_sup = model(**enc_l, labels=y_l).loss

                x_u_w = [weak_augment(t) for t in ub["text"]]
                x_u_s = [strong_augment(t) for t in ub["text"]]
                enc_w = tokenize_batch(tokenizer, x_u_w, max_len)
                enc_s = tokenize_batch(tokenizer, x_u_s, max_len)
                enc_w = {k: v.to(DEVICE) for k, v in enc_w.items()}
                enc_s = {k: v.to(DEVICE) for k, v in enc_s.items()}

                with torch.no_grad():
                    probs_w = torch.softmax(model(**enc_w).logits, dim=-1)
                    conf, pseudo = torch.max(probs_w, dim=-1)
                    mask = (conf >= tau).float()

                logits_s = model(**enc_s).logits
                loss_u_all = nn.CrossEntropyLoss(reduction="none")(logits_s, pseudo)
                loss_u = (loss_u_all * mask).mean()

                loss = loss_sup + lambda_u * loss_u
                total_loss += loss.item()

                opt.zero_grad(); loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                opt.step(); scheduler.step()

            # Self-Training
            model.eval()
            preds_info = []
            for batch in DataLoader(unlabeled_df.to_dict("records"),
                                    batch_size=64, shuffle=False):
                enc = tokenize_batch(tokenizer, batch["text"], max_len)
                enc = {k: v.to(DEVICE) for k, v in enc.items()}
                with torch.no_grad():
                    probs = torch.softmax(model(**enc).logits, dim=-1)
                    conf, pred = torch.max(probs, dim=-1)
                for t, c, p in zip(batch["text"],
                                   conf.cpu().numpy().tolist(),
                                   pred.cpu().numpy().tolist()):
                    preds_info.append((t, c, p))
            preds_info.sort(key=lambda x: x[1], reverse=True)
            k = int(len(preds_info) * selftrain_top_frac)
            if k > 0:
                to_add = preds_info[:k]
                add_df = pd.DataFrame({"text": [x[0] for x in to_add],
                                       "labels": [x[2] for x in to_add]})
                labeled_df = pd.concat([labeled_df, add_df], ignore_index=True)
                labeled_df = labeled_df.sample(frac=1.0, random_state=SEED).reset_index(drop=True)
                unlabeled_df = unlabeled_df.iloc[:max(1, len(unlabeled_df) - k)].reset_index(drop=True)

            dev_macro, _, _, _ = eval_model(model, tokenizer, dev_df, max_len)
            history['epoch'].append(ep)
            history['dev_macro'].append(dev_macro)
            history['train_loss'].append(total_loss / len(labeled_loader))
            history['n_labeled'].append(len(labeled_df))
            history['n_unlabeled'].append(len(unlabeled_df))
            print(f"[Epoch {ep}] Dev MacroF1={dev_macro:.4f} | Loss={total_loss/len(labeled_loader):.4f} | "
                  f"Labeled={len(labeled_df)} | Unlabeled={len(unlabeled_df)} | "
                  f"⏱{(time.time()-t_ep)/60:.1f}m")

            if dev_macro > best_dev:
                best_dev = dev_macro
                best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

        if best_state is not None:
            model.load_state_dict(best_state)
        test_macro, test_weighted, rep, cm = eval_model(model, tokenizer, test_df, max_len)
        return {"best_dev_macro": best_dev, "test_macro": test_macro,
                "test_weighted": test_weighted, "report": rep,
                "confusion": cm, "history": history,
                "model": model, "tokenizer": tokenizer}

    train_df, dev_df, test_df, class_names, num_labels = load_and_prepare(CFG)
    print(f"✅ Train: {len(train_df)} | Dev: {len(dev_df)} | Test: {len(test_df)}")
    print(f"📌 Classes ({num_labels}): {class_names}")

    labeled, unlabeled = split_labeled_unlabeled(train_df, labeled_ratio=0.2)
    print(f"✅ Labeled: {len(labeled)} | Unlabeled: {len(unlabeled)}")

    print(f"\n🚀 شروع FixMatch ({FIXMATCH_EPOCHS} اپوک)...")
    t0 = time.time()
    results = train_fixmatch(
        labeled_df=labeled, unlabeled_df=unlabeled,
        dev_df=dev_df, test_df=test_df,
        model_name=str(DOMAIN_MODEL_DIR),
        num_labels=num_labels,
        epochs=FIXMATCH_EPOCHS, tau=0.95, selftrain_top_frac=0.05)
    total_time = (time.time() - t0) / 60
    print(f"\n⏱ زمان کل: {total_time:.1f} دقیقه")
    print(f"✅ Best Dev Macro-F1: {results['best_dev_macro']:.4f}")
    print(f"✅ Test Macro-F1:      {results['test_macro']:.4f}")
    print(f"✅ Test Weighted-F1:   {results['test_weighted']:.4f}")

    results["model"].save_pretrained(str(FIXMATCH_MODEL_DIR))
    results["tokenizer"].save_pretrained(str(FIXMATCH_MODEL_DIR))

    bundle = {
        "dataset": DATASET_TO_RUN, "description": CFG["description"],
        "best_dev_macro": results["best_dev_macro"],
        "test_macro": results["test_macro"],
        "test_weighted": results["test_weighted"],
        "report": results["report"], "confusion": results["confusion"],
        "history": results["history"], "class_names": class_names,
        "num_sub_labels": num_labels, "total_time_min": total_time,
    }
    with open(FIXMATCH_DIR / "fixmatch_bundle.pkl", "wb") as f:
        pickle.dump(bundle, f)
    test_df.to_csv(FIXMATCH_DIR / "test_df.csv", index=False)
    dev_df.to_csv(FIXMATCH_DIR / "dev_df.csv", index=False)

    del results
    gc.collect(); torch.cuda.empty_cache()


