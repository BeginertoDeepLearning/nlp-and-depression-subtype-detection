def predict_proba(texts, max_len=128, batch_size=32):
    model.eval()
    probs_all = []
    texts = list(texts)
    for i in range(0, len(texts), batch_size):
        enc = tokenize_xai(texts[i:i+batch_size], max_len)
        enc = {k: v.to(DEVICE) for k, v in enc.items()}
        with torch.no_grad():
            probs_all.append(torch.softmax(model(**enc).logits, dim=-1).cpu().numpy())
    return np.vstack(probs_all)

