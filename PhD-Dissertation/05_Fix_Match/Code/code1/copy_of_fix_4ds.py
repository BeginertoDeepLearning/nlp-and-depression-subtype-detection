def load_and_prepare(cfg):
    if cfg["mode"] == "single":
        df = pd.read_csv(str(cfg["path"]), encoding=cfg["encoding"])
        df = df.dropna(subset=[cfg["text_col"], cfg["label_col"]])
        df = df[[cfg["text_col"], cfg["label_col"]]].rename(
            columns={cfg["text_col"]: "text", cfg["label_col"]: "labels"})
        df["text"] = df["text"].astype(str)
        df["labels"] = df["labels"].astype(str)

        if cfg["control_labels"]:
            before = len(df)
            df = df[~df["labels"].isin(cfg["control_labels"])].reset_index(drop=True)
            print(f"🗑️  حذف کنترل {cfg['control_labels']}: {before} → {len(df)}")

        le = LabelEncoder()
        df["labels"] = le.fit_transform(df["labels"])
        class_names = list(le.classes_)

        train_df, temp_df = train_test_split(
            df, test_size=cfg["test_size"], random_state=SEED, stratify=df["labels"])
        dev_df, test_df = train_test_split(
            temp_df, test_size=0.5, random_state=SEED, stratify=temp_df["labels"])
        return train_df, dev_df, test_df, class_names, len(class_names)

    else:
        train_df = pd.read_csv(str(cfg["train_path"]), encoding=cfg["encoding"])
        test_df = pd.read_csv(str(cfg["test_path"]), encoding=cfg["encoding"])

        train_df = train_df.dropna(subset=[cfg["text_col"], cfg["label_col"]])
        test_df = test_df.dropna(subset=[cfg["text_col"], cfg["label_col"]])
        train_df = train_df[[cfg["text_col"], cfg["label_col"]]].rename(
            columns={cfg["text_col"]: "text", cfg["label_col"]: "labels"})
        test_df = test_df[[cfg["text_col"], cfg["label_col"]]].rename(
            columns={cfg["text_col"]: "text", cfg["label_col"]: "labels"})
        train_df["text"] = train_df["text"].astype(str)
        test_df["text"] = test_df["text"].astype(str)
        train_df["labels"] = train_df["labels"].astype(str)
        test_df["labels"] = test_df["labels"].astype(str)

        if cfg["control_labels"]:
            train_df = train_df[~train_df["labels"].isin(cfg["control_labels"])]
            test_df = test_df[~test_df["labels"].isin(cfg["control_labels"])]
            print(f"🗑️  حذف کنترل — Train: {len(train_df)} | Test: {len(test_df)}")

        le = LabelEncoder()
        all_labels = pd.concat([train_df["labels"], test_df["labels"]]).unique()
        le.fit(all_labels)
        train_df["labels"] = le.transform(train_df["labels"])
        test_df["labels"] = le.transform(test_df["labels"])
        class_names = list(le.classes_)

        train_df, dev_df = train_test_split(
            train_df, test_size=cfg["val_size"], random_state=SEED, stratify=train_df["labels"])
        return train_df, dev_df, test_df, class_names, len(class_names)


