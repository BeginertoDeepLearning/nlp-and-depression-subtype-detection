import os, re, pickle, time
import numpy as np
import pandas as pd
import nltk
from pathlib import Path
from nltk.corpus import stopwords
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC
from sklearn.naive_bayes import MultinomialNB
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             f1_score, classification_report, confusion_matrix)
from sklearn.preprocessing import LabelEncoder

nltk.download('stopwords', quiet=True)
nltk.download('punkt', quiet=True)

# --- اتصال Drive ---
from google.colab import drive
drive.mount('/content/drive')

DRIVE_BASE = Path("/content/drive/MyDrive/nusrat_data")
DATA_FILE = DRIVE_BASE / "data" / "dataset.csv"
SVM_DIR = DRIVE_BASE / "models" / "svm_5class"
SVM_DIR.mkdir(parents=True, exist_ok=True)
RESULTS_DIR = DRIVE_BASE / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

BUNDLE_PATH = SVM_DIR / "svm_bundle.pkl"

# --- بررسی اینکه قبلاً اجرا شده؟ ---
if BUNDLE_PATH.exists():
    print(f"✅ باندل SVM ۵ کلاسه قبلاً ذخیره شده: {BUNDLE_PATH}")
    print("   برای اجرای مجدد، فایل را حذف کنید و سلول را دوباره اجرا کنید.")
else:
    print("🔨 شروع آموزش SVM ۵ کلاسه...")

    # ============================================
    # بارگذاری دیتاست
    # ============================================
    df = pd.read_csv(str(DATA_FILE), encoding='latin-1')
    print(f"✅ تعداد کل رکوردها: {len(df)}")

    df = df.dropna(subset=['Tweets', 'Labels']).reset_index(drop=True)

    # --- پاکسازی متن ---
    stop_words = set(stopwords.words('english'))

    def clean_text(text):
        if not isinstance(text, str):
            return ""
        text = text.lower()
        text = re.sub(r'\d+', '', text)
        text = re.sub(r'[^\w\s]', '', text)
        text = ' '.join([w for w in text.split() if w not in stop_words])
        return text.strip()

    df['clean_text'] = df['Tweets'].apply(clean_text)
    df = df[df['clean_text'].str.len() > 0].reset_index(drop=True)
    print(f"✅ بعد از پاکسازی: {len(df)}")

    # ============================================
    # کدگذاری اولیه برچسب‌ها
    # ============================================
    label_encoder_initial = LabelEncoder()
    df['label_encoded'] = label_encoder_initial.fit_transform(df['Labels'])

    print(f"\n📌 نگاشت برچسب‌ها (قبل از حذف کنترل):")
    for i, cls in enumerate(label_encoder_initial.classes_):
        print(f"   {i}: {cls}")

    # ============================================
    # ⚠️ حذف کلاس کنترل ('no') - مسئله ۵ کلاسه می‌شود
    # ============================================
    control_label_id = None
    for cls_name, cls_id in zip(label_encoder_initial.classes_,
                                 label_encoder_initial.transform(label_encoder_initial.classes_)):
        if cls_name.lower() == 'no':
            control_label_id = cls_id
            break

    if control_label_id is None:
        print("⚠️ کلاس 'no' پیدا نشد. از همه‌ی کلاس‌ها استفاده می‌شود.")
    else:
        print(f"\n🗑️ حذف کلاس کنترل '{label_encoder_initial.classes_[control_label_id]}' (کد {control_label_id})")
        df = df[df['label_encoded'] != control_label_id].reset_index(drop=True)
        print(f"✅ بعد از حذف کنترل: {len(df)}")

    # --- Re-encode پیوسته (0 تا 4) ---
    label_encoder = LabelEncoder()
    df['label_encoded'] = label_encoder.fit_transform(df['Labels'])

    print(f"\n📌 نگاشت نهایی (۵ کلاسه):")
    for i, cls in enumerate(label_encoder.classes_):
        print(f"   {i}: {cls}")

    print(f"\n📊 توزیع کلاس‌ها:")
    print(df['Labels'].value_counts())

    # ============================================
    # تقسیم داده
    # ============================================
    X = df['clean_text'].values
    y = df['label_encoded'].values

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )
    print(f"\n✅ Train: {len(X_train)} | Test: {len(X_test)}")

    # ============================================
    # TF-IDF
    # ============================================
    vectorizer = TfidfVectorizer(
        max_features=30000, ngram_range=(1, 2),
        min_df=2, sublinear_tf=True
    )
    X_train_tfidf = vectorizer.fit_transform(X_train)
    X_test_tfidf = vectorizer.transform(X_test)
    print(f"✅ ابعاد TF-IDF: Train={X_train_tfidf.shape}, Test={X_test_tfidf.shape}")

    # ============================================
    # چهار طبقه‌بند
    # ============================================
    classifiers = {
        'Logistic Regression': LogisticRegression(
            max_iter=2000, class_weight='balanced',
            random_state=42, multi_class='multinomial'
        ),
        'Linear SVM': LinearSVC(
            C=1.0, class_weight='balanced',
            random_state=42, max_iter=5000
        ),
        'Multinomial Naive Bayes': MultinomialNB(alpha=1.0),
        'Random Forest': RandomForestClassifier(
            n_estimators=300, class_weight='balanced',
            random_state=42, n_jobs=-1
        )
    }

    # ============================================
    # آموزش و ارزیابی
    # ============================================
    results = {}
    training_times = {}

    for name, clf in classifiers.items():
        print(f"\n{'='*60}\n🔄 {name}\n{'='*60}")

        start = time.time()
        clf.fit(X_train_tfidf, y_train)
        training_times[name] = time.time() - start

        y_pred = clf.predict(X_test_tfidf)

        acc = accuracy_score(y_test, y_pred)
        macro_p = precision_score(y_test, y_pred, average='macro', zero_division=0)
        macro_r = recall_score(y_test, y_pred, average='macro', zero_division=0)
        macro_f1 = f1_score(y_test, y_pred, average='macro', zero_division=0)
        weighted_f1 = f1_score(y_test, y_pred, average='weighted', zero_division=0)

        results[name] = {
            'Accuracy': acc * 100,
            'Precision': macro_p * 100,
            'Recall': macro_r * 100,
            'F1-Score': macro_f1 * 100,
            'Weighted-F1': weighted_f1 * 100,
            'y_pred': y_pred,
            'training_time': training_times[name],
        }
        print(f"   Accuracy: {acc*100:.2f}% | Macro-F1: {macro_f1*100:.2f}% | زمان: {training_times[name]:.2f}s")
        print(f"\n   Classification Report:")
        print(classification_report(y_test, y_pred,
                                     target_names=label_encoder.classes_,
                                     zero_division=0))

    # ============================================
    # جدول خلاصه
    # ============================================
    results_df = pd.DataFrame({
        name: {
            'Accuracy (%)': m['Accuracy'],
            'Precision (%)': m['Precision'],
            'Recall (%)': m['Recall'],
            'Macro F1 (%)': m['F1-Score'],
            'Weighted F1 (%)': m['Weighted-F1'],
            'Training Time (s)': m['training_time'],
        }
        for name, m in results.items()
    }).T

    print("\n" + "="*80)
    print("📊 جدول مقایسه نهایی (۵ کلاسه)")
    print("="*80)
    print(results_df.round(2).to_string())

    # ============================================
    # 🔒 ذخیره‌ی همه چیز در یک باندل
    # ============================================
    bundle = {
        'df': df,
        'classifiers': classifiers,
        'vectorizer': vectorizer,
        'label_encoder': label_encoder,
        'results': results,
        'results_df': results_df,
        'training_times': training_times,
        'X_train': X_train, 'X_test': X_test,
        'y_train': y_train, 'y_test': y_test,
        'X_train_tfidf': X_train_tfidf,
        'X_test_tfidf': X_test_tfidf,
    }

    with open(BUNDLE_PATH, 'wb') as f:
        pickle.dump(bundle, f)

    bundle_size = os.path.getsize(BUNDLE_PATH) / 1024 / 1024
    print(f"\n✅ باندل ذخیره شد: {BUNDLE_PATH} ({bundle_size:.2f} MB)")

    # ذخیره‌ی جدول نتایج
    results_df.round(4).to_csv(RESULTS_DIR / "svm_5class_results.csv")
    print(f"✅ جدول نتایج ذخیره شد: {RESULTS_DIR / 'svm_5class_results.csv'}")

    # === خلاصه ===
    best = max(results, key=lambda x: results[x]['F1-Score'])
    print(f"\n🏆 بهترین مدل: {best}")
    print(f"   Macro-F1: {results[best]['F1-Score']:.2f}%")
    print(f"   Weighted-F1: {results[best]['Weighted-F1']:.2f}%")
    print(f"   Accuracy: {results[best]['Accuracy']:.2f}%")

