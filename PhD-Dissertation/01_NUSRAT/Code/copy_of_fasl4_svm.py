# LinearSVC فاقد predict_proba است. از decision_function + softmax استفاده می‌کنیم.
def predict_proba_svm(texts):
    """ورودی: لیست متن؛ خروجی: احتمال ۵ کلاس"""
    cleaned = [clean_text(t) for t in texts]
    X = vectorizer.transform(cleaned)
    decision = svm_model.decision_function(X)
    # Softmax برای تبدیل decision به احتمال
    exp_d = np.exp(decision - decision.max(axis=1, keepdims=True))
    return exp_d / exp_d.sum(axis=1, keepdims=True)


